const productImage = (query, seed) => {
  if (mainPhotoBySeed[seed]) {
    return unsplashPhoto(mainPhotoBySeed[seed]);
  }

  const lowerQuery = query.toLowerCase();
  const matchedCollection = photoCollections.find(({ terms }) =>
    terms.some((term) => lowerQuery.includes(term))
  );
  const photos = matchedCollection?.photos || photoCollections[0].photos;

  return unsplashPhoto(photos[seed % photos.length]);
};

